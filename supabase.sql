drop policy if exists "admin img delete" on storage.objects;
create policy "admin img insert" on storage.objects for insert to authenticated with check (bucket_id='product-images' and public.is_admin());
create policy "admin img update" on storage.objects for update to authenticated using (bucket_id='product-images' and public.is_admin());
create policy "admin img delete" on storage.objects for delete to authenticated using (bucket_id='product-images' and public.is_admin());

