-- CELESTETARA database. Run this whole file once in Supabase > SQL Editor.
create table if not exists public.admins(email text primary key);
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.admins a where lower(a.email)=lower(coalesce(auth.jwt()->>'email','')));
$$;
create table if not exists public.categories(
  id integer generated by default as identity primary key,
  slug text unique not null check (slug ~ '^[a-z0-9-]+$'),
  name text not null, sizes text[] not null default '{}',
  sort integer not null default 0, active boolean not null default true);
create table if not exists public.products(
  id integer generated by default as identity primary key,
  category_id integer not null references public.categories(id) on delete restrict,
  name text not null, description text not null default '', stone text,
  intention text not null default 'peace' check (intention in ('love','abundance','protection','confidence','peace','focus')),
  tone text not null default 'soft' check (tone in ('warm','cool','dark','soft')),
  color text not null default '#c9a96e',
  regular_price integer not null check (regular_price>0),
  sale_price integer check (sale_price is null or (sale_price>0 and sale_price<regular_price)),
  stock integer not null default 0 check (stock>=0),
  in_stock boolean not null default true,
  images text[] not null default '{}', active boolean not null default true,
  created_at timestamptz not null default now());
create table if not exists public.coupons(
  code text primary key check (code ~ '^[A-Z0-9_-]{2,30}$'),
  type text not null check (type in ('percent','flat')),
  value integer not null check (value>0 and (type<>'percent' or value<=100)),
  min_order integer not null default 0, max_uses integer, used_count integer not null default 0,
  expires_at timestamptz, active boolean not null default true);
create table if not exists public.orders(
  id uuid primary key default gen_random_uuid(), created_at timestamptz not null default now(), paid_at timestamptz,
  razorpay_order_id text unique, razorpay_payment_id text,
  payment_status text not null default 'pending' check (payment_status in ('pending','paid','failed')),
  order_status text not null default 'new' check (order_status in ('new','processing','shipped','delivered','cancelled')),
  customer_name text not null, phone text not null, email text not null,
  address text not null, city text not null, state text not null, pin text not null,
  subtotal integer not null, discount integer not null default 0, total integer not null,
  coupon_code text, admin_notes text not null default '', dedupe_key text);
create table if not exists public.order_items(
  id integer generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id integer references public.products(id) on delete set null,
  product_name text not null, size text, qty integer not null check (qty>0),
  unit_price integer not null, custom jsonb);
create table if not exists public.inventory_log(
  id integer generated by default as identity primary key,
  product_id integer references public.products(id) on delete set null,
  change integer not null, reason text not null, order_id uuid,
  created_at timestamptz not null default now());
create index if not exists orders_created_idx on public.orders(created_at desc);
create index if not exists orders_dedupe_idx on public.orders(dedupe_key,created_at desc);
create index if not exists items_order_idx on public.order_items(order_id);
create index if not exists products_cat_idx on public.products(category_id);

-- Row Level Security: everything locked, then opened only to admins (and public product reads).
alter table public.admins enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.coupons enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.inventory_log enable row level security;
do $$ declare t text; begin
  foreach t in array array['admins','categories','products','coupons','orders','order_items','inventory_log'] loop
    execute format('drop policy if exists "admin all" on public.%I',t);
    execute format('create policy "admin all" on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())',t);
  end loop; end $$;
drop policy if exists "public read" on public.categories;
create policy "public read" on public.categories for select to anon, authenticated using (active);
drop policy if exists "public read" on public.products;
create policy "public read" on public.products for select to anon, authenticated using (active);
-- No policy for anon on coupons, orders, order_items, inventory_log, admins: customers cannot read or write them.

-- Admin stock adjustment (logged).
create or replace function public.admin_adjust_stock(p_id integer,p_delta integer,p_reason text) returns integer
language plpgsql security definer set search_path=public as $$
declare n integer;
begin
  if not public.is_admin() then raise exception 'not allowed'; end if;
  update products set stock=greatest(0,stock+p_delta) where id=p_id returning stock into n;
  insert into inventory_log(product_id,change,reason) values(p_id,p_delta,coalesce(p_reason,'manual'));
  return n;
end $$;
revoke all on function public.admin_adjust_stock(integer,integer,text) from public, anon;
grant execute on function public.admin_adjust_stock(integer,integer,text) to authenticated;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- Called only by the server (service role) after Razorpay confirms payment. Safe to call twice.
create or replace function public.finalize_paid_order(p_rzp_order text,p_payment text) returns text
language plpgsql security definer set search_path=public as $$
declare o public.orders; i record;
begin
  select * into o from orders where razorpay_order_id=p_rzp_order for update;
  if not found then return 'not_found'; end if;
  if o.payment_status='paid' then return 'already_paid'; end if;
  update orders set payment_status='paid',razorpay_payment_id=p_payment,paid_at=now() where id=o.id;
  for i in select * from order_items where order_id=o.id and product_id is not null loop
    update products set stock=greatest(0,stock-i.qty) where id=i.product_id;
    insert into inventory_log(product_id,change,reason,order_id) values(i.product_id,-i.qty,'order paid',o.id);
  end loop;
  if o.coupon_code is not null then update coupons set used_count=used_count+1 where code=o.coupon_code; end if;
  return 'paid';
end $$;
revoke all on function public.finalize_paid_order(text,text) from public, anon, authenticated;
grant execute on function public.finalize_paid_order(text,text) to service_role;

